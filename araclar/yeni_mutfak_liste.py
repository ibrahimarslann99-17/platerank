ALERJENLER = {'et','balik','sut','yumurta','gluten','kuruyemis','soya','baklagil'}

def satir(t):
    mutfak, tur, ad, ad_en, arama, g, alr, diyet = t
    a = [x for x in alr.split(',') if x]
    d = [x for x in diyet.split(',') if x]
    assert set(a) <= ALERJENLER, (ad, a)
    assert not ('vegan' in d and ({'sut','yumurta','et','balik'} & set(a))), ad
    assert not ('vejetaryen' in d and ({'et','balik'} & set(a))), ad
    if 'vegan' in d and 'vejetaryen' not in d:
        d = ['vejetaryen', 'vegan']
    assert 2 <= len(ad) <= 60, ad
    return {'mutfak': mutfak, 'tur': tur, 'ad': ad, 'ad_en': ad_en, 'arama': arama,
            'porsiyon_g': g, 'alerjenler': a, 'diyet': d}

